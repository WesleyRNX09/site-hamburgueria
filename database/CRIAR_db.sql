-- Mantém atualizado_em no UPDATE, papel do ON UPDATE CURRENT_TIMESTAMP do MySQL.
CREATE OR REPLACE FUNCTION definir_atualizado_em()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
  NEW.atualizado_em := CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$;

