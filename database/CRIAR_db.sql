  status VARCHAR(30) NOT NULL DEFAULT 'ativo',
  -- Ciclo de vida: suspender pede motivo; arquivar exige estar suspenso antes
  -- e guarda quem arquivou. Nenhum dado da loja é apagado.
  suspenso_em TIMESTAMPTZ NULL,
  motivo_suspensao VARCHAR(280) NULL,
  arquivado_em TIMESTAMPTZ NULL,
  arquivado_por BIGINT NULL,
  -- Token do QR Code único da equipe: um por estabelecimento, criado sob
  -- demanda pelo painel e trocado quando o administrador quiser invalidar os
  -- códigos já impressos.
  token_acesso_garcom VARCHAR(160) NULL,
  plano VARCHAR(50) NOT NULL DEFAULT 'basico',
  status_assinatura VARCHAR(30) NOT NULL DEFAULT 'ativa',
  vencimento_assinatura_em TIMESTAMPTZ,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uk_estabelecimentos_slug UNIQUE (slug),
  CONSTRAINT uk_estabelecimentos_dominio UNIQUE (dominio_personalizado),
  CONSTRAINT uk_estabelecimentos_token_garcom UNIQUE (token_acesso_garcom),
  CONSTRAINT chk_estabelecimentos_slug_preenchido
    CHECK (CHAR_LENGTH(TRIM(slug)) > 0),
  CONSTRAINT chk_estabelecimentos_status
    CHECK (status IN ('ativo', 'suspenso', 'arquivado')),
  CONSTRAINT chk_estabelecimentos_dominio_preenchido
    CHECK (dominio_personalizado IS NULL OR CHAR_LENGTH(TRIM(dominio_personalizado)) > 0)
);

