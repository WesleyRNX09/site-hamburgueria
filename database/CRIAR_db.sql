-- Fora do Supabase os papéis anon/authenticated não existem: o bloco só
-- revoga o que houver.
DO $$
DECLARE
  papel TEXT;
BEGIN
  FOREACH papel IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = papel) THEN
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM %I', current_schema(), papel);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM %I', current_schema(), papel);
      EXECUTE format('REVOKE EXECUTE ON FUNCTION definir_atualizado_em() FROM %I', papel);
    END IF;
  END LOOP;
END;
$$;

