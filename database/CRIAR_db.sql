INSERT INTO estabelecimentos
  (nome_fantasia, slug, status, plano, status_assinatura)
VALUES
  ('Estabelecimento padrão', 'estabelecimento-padrao', 'ativo', 'basico', 'ativa')
ON CONFLICT (slug) DO NOTHING;

INSERT INTO configuracoes_estabelecimento (id_estabelecimento)
SELECT id_estabelecimento
FROM estabelecimentos
WHERE slug = 'estabelecimento-padrao'
ON CONFLICT (id_estabelecimento) DO NOTHING;

INSERT INTO categorias (id_estabelecimento, id, nome, ordem, ativo)
SELECT e.id_estabelecimento, c.id, c.nome, c.ordem, 1
FROM estabelecimentos e
CROSS JOIN (VALUES
  (1, 'Hambúrgueres', 1),
  (2, 'Combos', 2),
  (3, 'Porções', 3),
  (4, 'Bebidas', 4)
) AS c (id, nome, ordem)
WHERE e.slug = 'estabelecimento-padrao'
ON CONFLICT (id) DO NOTHING;

-- As categorias entram com id fixo: a sequência precisa continuar depois delas.
SELECT setval(
  pg_get_serial_sequence('categorias', 'id'),
  (SELECT COALESCE(MAX(id), 0) + 1 FROM categorias),
  false
);

