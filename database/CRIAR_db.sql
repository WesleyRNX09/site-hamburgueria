-- Instalação completa da estrutura multiempresa em PostgreSQL (Supabase).
-- Uso exclusivo em um schema vazio. No Supabase: SQL Editor -> cole este
-- arquivo inteiro -> Run. Não cria nem seleciona banco: usa o schema atual
-- (public, no Supabase).
--
-- Cria somente o estabelecimento inicial de compatibilidade, sem contas
-- administrativas nem dados demonstrativos. Tudo roda numa transação: se uma
-- instrução falhar, nada fica pela metade.
--
-- Convenções:
--   * horários em TIMESTAMPTZ (instante absoluto); o pool da aplicação fixa a
--     sessão em UTC para os textos de data sem fuso que o backend envia;
--   * flags em SMALLINT 0/1, o mesmo valor que o backend lê e grava;
--   * valores em centavos em BIGINT com CHECK >= 0 (cobre o limite de
--     4.294.967.295 que o backend valida);
--   * unicidade de usuário, e-mail e nomes do catálogo ignora maiúsculas
--     (índices em LOWER(...)), como a collation _ci do MySQL fazia;
--   * RLS ligado em todas as tabelas, sem nenhuma política: a API REST do
--     Supabase (papéis anon/authenticated) não lê nem grava nada. O backend
--     conecta como dono das tabelas e não é afetado.

BEGIN;

SET LOCAL TIME ZONE 'UTC';

